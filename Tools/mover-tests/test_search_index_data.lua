local NS = ...

-- ============================================================
-- THE PREBUILT SEARCH INDEX -- DandersFrames_Options/Features/SearchIndexData.lua
-- ------------------------------------------------------------
-- The file is generated outside this repo (its header names the generator) and
-- read by Features/SearchPrebuilt.lua. This pins that it loads, that its shape is
-- what the reader expects, and that it holds a sane amount of the settings the
-- side menu's filter has to find without building a page.
-- ☠ ONE LUA RUNTIME FOR EVERY SUITE: the DandersFrames global is restored.
-- ============================================================

local savedDF = DandersFrames

local DF = { Search = {}, L = setmetatable({}, { __index = function(_, k) return k end }) }
DF.GUI = { Pages = {} }
DandersFrames = DF
load_options_file_into("Features/SearchIndexData.lua", NS)
load_options_file_into("Features/SearchPrebuilt.lua", NS)
DandersFrames = savedDF

local Search = DF.Search
local data = Search.PrebuiltIndex

print("-- Search index data: loads and has its parts")
check(type(data) == "table", "data: the file defines Search.PrebuiltIndex")
data = data or { S = {}, C = {}, P = {} }
check(type(data.version) == "string" and data.version:match("^v%d"), "data: names the addon version it was made from")
check(type(data.commit) == "string" and #data.commit >= 7, "data: names the addon commit it was made from")
check(type(data.S) == "table" and type(data.C) == "table" and type(data.P) == "table", "data: strings, conditions, pages")

local SRC = options_file_source("Features/SearchIndexData.lua")
check(SRC:find("Generated by", 1, true) ~= nil, "data: the header names its generator")

print("-- Search index data: every row is well formed")
local rows, pages, bad, titles = 0, 0, 0, 0
local nS, nC = #data.S, #data.C
for id, list in pairs(data.P) do
    pages = pages + 1
    if type(id) ~= "string" or not id:match("^[%w_]+$") then bad = bad + 1 end
    if #list % 6 ~= 0 then bad = bad + 1 end
    for i = 1, #list, 6 do
        rows = rows + 1
        local l, t, k, tip, c, f = list[i], list[i + 1], list[i + 2], list[i + 3], list[i + 4], list[i + 5]
        if not (l >= 1 and l <= nS) then bad = bad + 1 end
        for _, v in ipairs({ t, k, tip }) do
            if not (v >= 0 and v <= nS) then bad = bad + 1 end
        end
        if not (c >= 0 and c <= nC) then bad = bad + 1 end
        if f ~= 0 and f ~= 1 then bad = bad + 1 end
        if f == 1 then titles = titles + 1 end
    end
end
eq(bad, 0, "rows: every index points at a string or condition that exists")
eq(rows, data.rows, "rows: the header count matches the rows")
check(pages >= 100, "rows: covers the sidebar's pages (" .. pages .. ")")
check(rows >= 3000, "rows: a sane number of rows (" .. rows .. ")")
check(titles >= 300, "rows: card and header titles are there (" .. titles .. ")")
for _, cond in ipairs(data.C) do
    local ok = type(cond) == "table" and #cond >= 1
    for _, alt in ipairs(type(cond) == "table" and cond or {}) do
        if type(alt) ~= "table" or #alt % 2 ~= 0 or type(alt[1]) ~= "string" then ok = false end
    end
    if not ok then bad = bad + 1 end
end
eq(bad, 0, "conditions: alternatives of key, value pairs")

print("-- Search index data: holds what the reports were about")
local function PageHas(page, pred)
    for _, e in ipairs(Search:PrebuiltEntries(page) or {}) do
        if pred(e) then return true end
    end
    return false
end
check(PageHas("general_frame", function(e) return e.isSection and e.label == "Permanent Mover" end),
      "reports: the group Frame page has the Permanent Mover card")
check(not PageHas("uf_player_frame", function(e) return e.dbKey == "permanentMover" end),
      "reports: a unit frame's Frame page does not (the card is filtered off it)")
local resting = false
for id in pairs(data.P) do
    if id:match("^uf_player_") and PageHas(id, function(e) return e.dbKey == "restingIconEnabled" end) then resting = true end
end
check(resting, "reports: a player unit page has the Resting Icon setting")
check(PageHas("uf_target_castbar", function(e) return e.dbKey == "castbarEnabled" end),
      "reports: the target's cast bar page has its settings")

print("-- Search index data: entries come out resolved through the locale")
local list = Search:PrebuiltEntries("general_frame") or {}
local e = list[1] or {}
check(e.prebuilt and e.tab == "general_frame" and type(e.label) == "string" and e.labelEn ~= nil,
      "entries: prebuilt, on their page, with a label and its English key")
check(Search:PrebuiltEntries("general_frame") == list, "entries: made once per page and kept")
check(Search:PrebuiltEntries("no_such_page") == nil, "entries: an unknown page has none")
