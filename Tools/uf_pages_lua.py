"""Generate DandersFrames_Options/UnitFrames/PageData.lua from the unit-frames page inventory.

Input : docs/superpowers/specs/unitframes-build/uf-pages.json (generated by uf_build.py, git-ignored)
        DandersFrames_Options/GUI/Pages/*.lua (to resolve each DF card title to its section key)
Output: DandersFrames_Options/UnitFrames/PageData.lua (committed)

Usage: python Tools/uf_pages_lua.py

What the Lua table says, per unit-frames page:
  kind      short id; the page for unit U is "uf_<U>_<kind>"
  source    the DandersFrames party page whose builder draws it (nil: built by the UF pages)
  category  sidebar category (General / Display / Bars / Text / Auras / Indicators)
  title     enUS label (an L key)
  units     which units get the page
  cards     section key -> the units that see that card (a DF card not listed is never shown)
  hide      db key -> the units a control is hidden for (dropped from, or not relevant to, that unit)
  cardKeys  DF section key -> the db keys that card's controls write, for a card some of the
            page's units do not see (so a copy into that unit can leave them alone)
  later     the page is new to unit frames and waits for its runtime (not built yet)
Cards new to unit frames on a DF page (no DF section key) are listed under `laterCards` and skipped,
unless a page of their own draws them (SPLIT_CARDS: the Icons page's Unit group becomes the
"Unit Icons" page, because a card of ours may not be added to a page a party builder draws).
A built new page also carries `cards`: card slug (its title, lower case, words joined by _) ->
the units that card reaches.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "docs" / "superpowers" / "specs" / "unitframes-build" / "uf-pages.json"
PAGES = ROOT / "DandersFrames_Options" / "GUI" / "Pages"
OUT = ROOT / "DandersFrames_Options" / "UnitFrames" / "PageData.lua"

UNITS = ["player", "target", "targettarget", "focus", "focustarget", "pet", "boss"]

# Units the inventory never listed that get exactly another unit's pages, cards and
# hidden controls (v1.1 additions): unit -> the unit it mirrors.
#   focustarget  the focus's target is target of target's pattern on focus
MIRRORS = {"focustarget": "targettarget"}

def mirror(obj):
    """Every unit list in the inventory that names a mirrored unit's source names it too."""
    if isinstance(obj, list):
        out = [mirror(v) for v in obj]
        for unit, src in MIRRORS.items():
            if src in out and unit not in out:
                out.append(unit)
        return out
    if isinstance(obj, dict):
        return {k: mirror(v) for k, v in obj.items()}
    return obj

KIND = {
    "general_frame": "frame", "display_tooltips": "tooltips", "display_fading": "fading",
    "bars_health": "health", "bars_resource": "resource", "bars_absorb": "absorbs",
    "bars_healpred": "healpred", "uf_text": "text", "auras_buffs": "buffs",
    "auras_debuffs": "debuffs", "auras_defensiveicon": "defensive", "auras_dispel": "dispel",
    "uf_auradesigner": "auradesigner", "indicators_icons": "icons",
    "indicators_highlights": "highlights",
    # New to unit frames; their runtime arrives in later stages.
    "uf_bosslayout": "bosslayout", "uf_visibility": "visibility", "uf_portrait": "portrait",
    "uf_castbar": "castbar", "uf_classpower": "classpower", "uf_rings": "rings",
}
# New pages whose runtime is built: emitted without `later`, with the units their
# cards reach and the per-unit `hide` list; Pages.lua draws their controls.
BUILT_NEW = {"uf_visibility", "uf_castbar", "uf_classpower", "uf_portrait", "uf_bosslayout", "uf_rings"}
# Controls hidden for a unit on top of what the inventory says, because the runtime
# cannot honour them there: page id -> db key -> units.
#   castbarDetached on Boss: five boss cast bars share one settings table, so one
#   detached record would stack all five on one spot (CastBar.lua IsDetached).
EXTRA_HIDE = {"uf_castbar": {"castbarDetached": {"boss"}}}
# New cards on a DF page that get a built page of their own instead:
# source page id -> (kind, category, title) of the page that draws them.
SPLIT_CARDS = {"indicators_icons": ("unitIcons", "indicators", "Unit Icons")}
# Cards new since the inventory, added to a built page: kind -> [(card slug, units)].
#   class_decorations  Elite Dragon / Classification Border / Classification Colors
#                      (Indicators.lua): every unit with a classification, Boss
#                      included -- Boss has no Elite / Rare icon card, only these.
EXTRA_CARDS = {"unitIcons": [("class_decorations", {"target", "focus", "boss"})]}
# Units added to an inventory card since the inventory: page id -> card title -> units.
#   Selection Highlight  Target of Target / Focus Target: the unit is often you or
#                        your target, and the highlight runs there (only Target's
#                        own is off for good, Defaults.lua).
#   Elite / Rare         Boss: its frames draw the icon (Indicators.lua IN.ICONS),
#                        so it needs the card to switch it off.
#   Health Threshold     Every unit: the fade is DandersFrames' own (HealthFade.lua,
#   Fading               curve-based), it runs on any standalone frame, and "fade
#                        at full health" is as useful on a target as on the player.
# Units added to a whole page since the inventory: page id -> units. Every card follows.
#   Portrait  Target of Target / Focus Target: a Ring-style frame is round a portrait, so
#             without one its middle stays empty. Off by default (Defaults.lua).
EXTRA_PAGE_UNITS = {"uf_portrait": {"targettarget", "focustarget"}}
EXTRA_CARD_UNITS = {
    "indicators_highlights": {"Selection Highlight": {"targettarget", "focustarget"}},
    "indicators_icons": {"Elite / Rare": {"boss"}},
    "auras_debuffs": {"Highlight": {"target", "focus", "boss"}},
    "display_fading": {"Health Threshold Fading": {"target", "targettarget", "focus", "focustarget", "boss"}},
}

# New cards on a DF page that the party builder draws through its card door
# (page.dfExtraCards, UnitFrames/Pages.lua UFO.ExtraCards): page id -> card title ->
# the section key the builder opens it with. Listed like any DF card, so the page's
# `cards` filter reaches them per unit.
#   Detach     bars_resource (Auras.lua), after Position: the detached resource bar.
#   Purgeable  auras_buffs (Indicators.lua), in Effects: purgeable enemy buffs ringed.
HOOKED_CARDS = {
    "bars_resource": {"Detach": "resource_detached"},
    "auras_buffs": {"Purgeable": "buffs_purgeable"},
}

def slug(title):
    return re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")
# Section-key prefix of each DF page's cards (tools.OpenSection's collapseKey).
PREFIX = {
    "general_frame": "frame_", "display_tooltips": "tooltips_", "display_fading": "fading_",
    "bars_health": "health_", "bars_resource": "resource_", "bars_absorb": "absorbs_",
    "bars_healpred": "healpred_", "auras_buffs": "buffs_", "auras_debuffs": "debuffs_",
    "auras_defensiveicon": "defensiveicon_", "auras_dispel": "dispel_",
    "indicators_icons": "icons_", "indicators_highlights": "highlights_",
}

def section_keys():
    """(title, key) pairs from every OpenSection call and the Icons page's spec table."""
    pairs = []
    open_re = re.compile(r'OpenSection\(\s*L\["([^"]+)"\]\s*,\s*"([a-z_]+)"')
    grad_re = re.compile(r'L\["(Health Gradient)"\] or L\["(Missing Health Gradient)"\],\s*\n\s*'
                         r'\(prefix == "healthColor"\) and "([a-z_]+)" or "([a-z_]+)"')
    icon_re = re.compile(r'key = "([A-Za-z]+Icon)",[^\n]*section = L\["([^"]+)"\]')
    for f in sorted(PAGES.glob("*.lua")):
        text = f.read_text(encoding="utf-8")
        pairs += [(t, k) for t, k in open_re.findall(text)]
        for a, b, ka, kb in grad_re.findall(text):
            pairs += [(a, ka), (b, kb)]
        pairs += [(t, "icons_" + k) for k, t in icon_re.findall(text)]
    # Icon Text Settings is opened with its own literal key.
    return pairs

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def lua_set(units):
    return "{ " + ", ".join(f"{u} = true" for u in UNITS if u in units) + " }"

def main():
    data = mirror(json.loads(SRC.read_text(encoding="utf-8")))
    pairs = section_keys()
    out = []
    errors = []
    for p in data["pages"]:
        pid = p["pageId"]
        if pid == "uf_settings":
            continue                       # the module page: built by Pages.lua, not per unit
        kind = KIND[pid]
        page_extra = EXTRA_PAGE_UNITS.get(pid, set())
        units = [u for u in UNITS if u in p["units"] or u in page_extra]
        rec = {"kind": kind, "category": p["category"], "title": p["title"], "units": units}
        if p["origin"] == "new" and pid not in BUILT_NEW:
            rec["later"] = True
        if p["origin"] == "df":
            rec["source"] = pid
        cards, hide, later_cards = [], {}, []
        card_keys = {}                     # section key -> db keys, for partly hidden cards
        split = []                         # (title, units, controls) of SPLIT_CARDS cards
        for g in p["groups"]:
            for c in g["cards"]:
                extra = EXTRA_CARD_UNITS.get(pid, {}).get(c["title"], set()) | page_extra
                cu = [u for u in units if u in (c.get("units") or units) or u in extra]
                key = None
                if p["origin"] == "df":
                    want = PREFIX[pid]
                    hits = sorted({k for t, k in pairs if t == c["title"] and k.startswith(want)})
                    hooked = HOOKED_CARDS.get(pid, {}).get(c["title"])
                    if hooked:
                        hits = [hooked]
                    elif c.get("new"):
                        if pid in SPLIT_CARDS:
                            split.append((c["title"], cu, c["controls"]))
                        else:
                            later_cards.append(c["title"])
                        continue
                    if len(hits) != 1:
                        errors.append(f"{pid}: card {c['title']!r} -> {hits}")
                        continue
                    key = hits[0]
                    cards.append((key, cu))
                    if len(cu) < len(units):
                        ks = set()
                        for k in [c.get("tick")] + [ct.get("key") for ct in c["controls"]]:
                            if k:
                                ks.add(re.split(r"[\[.]", k)[0])
                        if ks:
                            card_keys[key] = sorted(ks)
                    for ct in c["controls"]:
                        k = ct.get("key")
                        if not k or "." in k or ct.get("new"):
                            continue
                        if ct.get("units"):
                            hidden = [u for u in cu if u not in ct["units"]]
                            if hidden:
                                hide.setdefault(k, set()).update(hidden)
                else:
                    cards.append((slug(c["title"]), cu))
                    if pid in BUILT_NEW:
                        for ct in c["controls"]:
                            k = ct.get("key")
                            if k and ct.get("units"):
                                hidden = [u for u in cu if u not in ct["units"]]
                                if hidden:
                                    hide.setdefault(k, set()).update(hidden)
        for k, us in EXTRA_HIDE.get(pid, {}).items():
            hide.setdefault(k, set()).update(u for u in us if u in units)
        rec["cards"], rec["hide"], rec["laterCards"] = cards, hide, later_cards
        rec["cardKeys"] = card_keys
        if pid in BUILT_NEW:
            rec["built"] = True
            rec["units"] = [u for u in units if any(u in cu for _, cu in cards)]
        if p["origin"] == "df":
            # A unit with no card on a DF page does not get the page (Fading on
            # Target of Target: every card there is filtered off for it).
            rec["units"] = [u for u in units if any(u in cu for _, cu in cards)]
        out.append(rec)
        if split:
            kind2, cat2, title2 = SPLIT_CARDS[pid]
            srec = {"kind": kind2, "category": cat2, "title": title2, "built": True,
                    "cards": [(slug(t), cu) for t, cu, _ in split], "hide": {}, "laterCards": []}
            for t, cu, controls in split:
                for ct in controls:
                    k = ct.get("key")
                    if k and ct.get("units"):
                        hidden = [u for u in cu if u not in ct["units"]]
                        if hidden:
                            srec["hide"].setdefault(k, set()).update(hidden)
            for key, us in EXTRA_CARDS.get(kind2, []):
                srec["cards"].append((key, [u for u in UNITS if u in us]))
            srec["units"] = [u for u in UNITS if any(u in cu for _, cu in srec["cards"])]
            out.append(srec)

    # Controls the build dropped from a DF card outright (uf_build.py drop_controls):
    # hidden for every unit. Found by diffing the DF inventory against the UF cards.
    df = {}
    for f in "ABC":
        path = SRC.parent / f"df-pages-{f}.json"
        for pg in json.loads(path.read_text(encoding="utf-8")):
            df[pg["pageId"]] = pg
    for rec in out:
        pid = rec.get("source")
        if not pid:
            continue
        uf = next(p for p in data["pages"] if p["pageId"] == pid)  # already mirrored
        for g in uf["groups"]:
            for c in g["cards"]:
                if c.get("new"):
                    continue
                dfc = next((x for sg in df[pid]["groups"] for x in sg["cards"] if x["title"] == c["title"]), None)
                if not dfc:
                    continue
                keep = {ct.get("key") for ct in c["controls"]}
                for ct in dfc["controls"]:
                    k = ct.get("key")
                    if k and "." not in k and k not in keep:
                        rec["hide"].setdefault(k, set()).update(rec["units"])

    if errors:
        print("UNRESOLVED CARDS:")
        for e in errors:
            print("  " + e)
        sys.exit(1)

    L = []
    L.append("-- GENERATED by Tools/uf_pages_lua.py from docs/superpowers/specs/unitframes-build/uf-pages.json.")
    L.append("-- Do not edit by hand: change the inventory (uf_build.py) or the generator and re-run it.")
    L.append("local DF = DandersFrames")
    L.append("if not DF then return end")
    L.append("")
    L.append("-- ============================================================")
    L.append("-- UNIT FRAMES PAGE RELEVANCE")
    L.append("-- Which settings pages, cards and controls each unit gets (spec section 3).")
    L.append("-- kind: page id is uf_<unit>_<kind>. source: the DF party page whose builder draws it.")
    L.append("-- cards: DF section key -> units that see that card; a DF card not listed never shows.")
    L.append("-- hide: db key -> units the control is hidden for. later: new page, runtime not built yet.")
    L.append("-- laterCards: cards new to unit frames on a DF page, waiting for their runtime.")
    L.append("-- cardKeys: section key -> db keys of a card some of the page's units do not see.")
    L.append("-- ============================================================")
    L.append("DF.UnitFramePageData = {")
    L.append("    units = { " + ", ".join(lua_str(u) for u in UNITS) + " },")
    L.append("    categories = {")
    for cid, label in data["nav"]:
        L.append(f"        {{ id = {lua_str(cid)}, label = {lua_str(label)} }},")
    L.append("    },")
    L.append("    pages = {")
    for rec in out:
        L.append("        {")
        L.append(f"            kind = {lua_str(rec['kind'])}, category = {lua_str(rec['category'])}, title = {lua_str(rec['title'])},")
        if rec.get("source"):
            L.append(f"            source = {lua_str(rec['source'])},")
        if rec.get("later"):
            L.append("            later = true,")
        L.append(f"            units = {lua_set(rec['units'])},")
        if rec.get("source"):
            L.append("            cards = {")
            for key, cu in rec["cards"]:
                L.append(f"                {key} = {lua_set(cu)},")
            L.append("            },")
            L.append("            hide = {")
            for key in sorted(rec["hide"]):
                L.append(f"                {key} = {lua_set(rec['hide'][key])},")
            L.append("            },")
            if rec["laterCards"]:
                L.append("            laterCards = { " + ", ".join(lua_str(t) for t in rec["laterCards"]) + " },")
            if rec.get("cardKeys"):
                L.append("            cardKeys = {")
                for key in sorted(rec["cardKeys"]):
                    L.append(f"                {key} = {{ " + ", ".join(lua_str(k) for k in rec["cardKeys"][key]) + " },")
                L.append("            },")
        elif rec.get("built"):
            L.append("            cards = {")
            for key, cu in rec["cards"]:
                L.append(f"                {key} = {lua_set(cu)},")
            L.append("            },")
            L.append("            hide = {")
            for key in sorted(rec["hide"]):
                L.append(f"                {key} = {lua_set(rec['hide'][key])},")
            L.append("            },")
        L.append("        },")
    L.append("    },")
    L.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} pages")

if __name__ == "__main__":
    main()
